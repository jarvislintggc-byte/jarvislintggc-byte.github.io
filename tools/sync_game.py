"""Keep editable root game modules and their versioned runtime output in sync."""
import argparse
from datetime import datetime
import hashlib
import json
from pathlib import Path
import re

MODULE_URL = re.compile(r'''(["'`])((?:\./|/runtime/)journey[^"'`<>\s?]*\.(?:mjs|js))(?:\?v=[\w-]+)?\1''')
ENTRY_URL = re.compile(r'''(["'`])(/journey-boot\.js|/runtime/journey\.js)(?:\?v=[\w-]+)?\1''')


def body(text):
    return re.sub(r'^(?:// (?:Generated by build.py;[^\n]*|Generated from [^\n]*)\n)+', '', text).strip()


def versioned(text, version, pattern=MODULE_URL):
    return pattern.sub(lambda m: m[1] + m[2] + '?v=' + version + m[1], text)


def sync(root, write=False):
    manifest_path = root / 'runtime/version.json'
    manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    sources = {p.name: p.read_text(encoding='utf-8') for p in sorted(root.glob('journey-*.mjs'))}
    sources['journey.js'] = (root / 'journey.js').read_text(encoding='utf-8')
    orphaned = set(manifest['modules']) - sources.keys()
    if orphaned:
        raise ValueError('Missing editable sources; nothing was written: ' + ', '.join(sorted(orphaned)))
    for name, text in sources.items():
        for match in MODULE_URL.finditer(text):
            target = match[2].split('/')[-1]
            if target not in sources:
                raise ValueError(f'{name} references a missing game module: {target}')
    dirty = set(manifest['modules']) != sources.keys()
    for name, text in sources.items():
        target = root / 'runtime' / name
        if not target.exists() or body(target.read_text(encoding='utf-8')) != body(text):
            dirty = True
    entry_files = [root / 'journey-boot.js'] + [root / p / 'index.html' for p in ['my-story', 'zh/my-story', 'ja/my-story']]
    entry_texts = {p: p.read_text(encoding='utf-8') for p in entry_files}
    if any(not ENTRY_URL.search(text) for text in entry_texts.values()):
        raise ValueError('A game loader URL is missing; nothing was written.')
    if not write:
        if dirty:
            raise ValueError('Game source and runtime differ. Run tools/sync_game.py --write.')
        for text in sources.values():
            if versioned(text, manifest['version']) != text:
                raise ValueError('Inconsistent game cache versions. Run tools/sync_game.py --write.')
        for text in entry_texts.values():
            if versioned(text, manifest['version'], ENTRY_URL) != text:
                raise ValueError('Inconsistent game cache versions. Run tools/sync_game.py --write.')
        return {'modules': len(sources), 'version': manifest['version'], 'synchronized': True}
    version = manifest['version']
    if dirty:
        digest = hashlib.sha256()
        for name, text in sorted(sources.items()):
            digest.update(name.encode())
            digest.update(versioned(body(text), 'GAME_VERSION').encode())
        version = digest.hexdigest()[:16]
    changes = {}
    for name, text in sources.items():
        source = versioned(text, version)
        changes[root / name] = source
        changes[root / 'runtime' / name] = f'// Generated from ../{name} by tools/sync_game.py. Edit the root source only.\n' + body(source) + '\n'
    for path, text in entry_texts.items():
        changes[path] = versioned(text, version, ENTRY_URL)
    manifest.update(version=version, modules=sorted(sources))
    changes[manifest_path] = json.dumps(manifest, indent=2) + '\n'
    changes = {p: text for p, text in changes.items() if not p.exists() or p.read_text(encoding='utf-8') != text}
    if changes:
        backup = root / '.local-knowledge/game-sync-backups' / datetime.now().strftime('%Y%m%d-%H%M%S-%f')
        for path in changes:
            if path.exists():
                target = backup / path.relative_to(root)
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(path.read_bytes())
        for path, text in changes.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8', newline='\n')
    return {'modules': len(sources), 'version': version, 'updated_files': len(changes)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--write', action='store_true')
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parent.parent)
    args = parser.parse_args()
    try:
        print(json.dumps(sync(args.root.resolve(), args.write)))
    except (ValueError, OSError, KeyError) as error:
        parser.exit(1, str(error) + '\n')


if __name__ == '__main__':
    main()

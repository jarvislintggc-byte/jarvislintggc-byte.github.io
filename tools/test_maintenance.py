from pathlib import Path
from html.parser import HTMLParser
import json
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parent.parent


class Meta(HTMLParser):
    def __init__(self):
        super().__init__()
        self.keys = []
    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'meta':
            key = attrs.get('property', attrs.get('name', ''))
            if key.startswith(('og:', 'twitter:')):
                self.keys.append(key)


class MaintenanceTests(unittest.TestCase):
    def test_home_share_metadata_is_unambiguous(self):
        for name in ['index.html', 'zh/index.html', 'ja/index.html']:
            with self.subTest(page=name):
                parser = Meta()
                parser.feed((ROOT / name).read_text(encoding='utf-8').split('</head>')[0])
                self.assertEqual(len(parser.keys), len(set(parser.keys)))
                self.assertIn('og:image', parser.keys)
                self.assertIn('twitter:card', parser.keys)

    def test_game_edit_is_detected_and_synchronized(self):
        script = ROOT / 'tools/sync_game.py'
        with tempfile.TemporaryDirectory(dir=ROOT / '.local-knowledge') as temp:
            root = Path(temp)
            (root / 'runtime').mkdir()
            sources = {'journey.js': "import './journey-engine.mjs?v=old';\n", 'journey-engine.mjs': 'export const value=1;\n'}
            for name, text in sources.items():
                (root / name).write_text(text, encoding='utf-8')
                (root / 'runtime' / name).write_text('// Generated by build.py; edit source.\n' + text, encoding='utf-8')
            (root / 'runtime/version.json').write_text(json.dumps({'version': 'old', 'entry': 'journey.js', 'modules': sorted(sources)}), encoding='utf-8')
            (root / 'journey-boot.js').write_text("import('/runtime/journey.js?v=old');", encoding='utf-8')
            for name in ['my-story', 'zh/my-story', 'ja/my-story']:
                (root / name).mkdir(parents=True)
                (root / name / 'index.html').write_text('<script src="/journey-boot.js?v=old"></script>', encoding='utf-8')
            def run(mode):
                return subprocess.run([sys.executable, str(script), mode, '--root', str(root)], capture_output=True, text=True)
            result = run('--check')
            self.assertEqual(result.returncode, 0, result.stderr)
            (root / 'journey-engine.mjs').write_text('export const value=2;\n', encoding='utf-8')
            self.assertNotEqual(run('--check').returncode, 0)
            result = run('--write')
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertIn('value=2', (root / 'runtime/journey-engine.mjs').read_text())
            version = json.loads((root / 'runtime/version.json').read_text())['version']
            self.assertNotEqual(version, 'old')
            self.assertIn('?v=' + version, (root / 'journey-boot.js').read_text())
            for name in ['my-story', 'zh/my-story', 'ja/my-story']:
                self.assertIn('?v=' + version, (root / name / 'index.html').read_text())
            self.assertEqual(run('--check').returncode, 0)
            before = (root / 'runtime/version.json').read_bytes()
            self.assertEqual(run('--write').returncode, 0)
            self.assertEqual(before, (root / 'runtime/version.json').read_bytes())
            runtime_before = (root / 'runtime/journey-engine.mjs').read_bytes()
            (root / 'journey-engine.mjs').unlink()
            self.assertNotEqual(run('--write').returncode, 0)
            self.assertEqual(runtime_before, (root / 'runtime/journey-engine.mjs').read_bytes())


if __name__ == '__main__':
    unittest.main()
